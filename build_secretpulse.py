#!/usr/bin/env python3
"""Build the single-file SecretPulse.py distribution from secretpulse/."""

import argparse
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
PACKAGE = ROOT / 'secretpulse'
DEFAULT_OUTPUT = ROOT / 'SecretPulse.py'

MODULES = (
    '_imports',
    'constants',
    'utils',
    'jwt',
    'license',
    'verification',
    'analysis',
    'discovery',
    'storage',
    'recon',
    'exposure',
    'reporting',
    'scanner',
    'cli',
)

INTERNAL_IMPORT = re.compile(r'^\s*from\s+(?:\.|secretpulse\b)')
DOCSTRING = re.compile(r'^\s*""".*"""\s*$')

HEADER = '''#!/usr/bin/env python3
"""SecretPulse v{version} — High-Signal Secret & API Exposure Scanner.

Generated single-file distribution. Source of truth: secretpulse/.
Rebuild with: python3 build_secretpulse.py
"""

# Generated by build_secretpulse.py — do not edit this file directly.

'''

FOOTER = """

if __name__ == '__main__':
    main()
"""


class BuildError(Exception):
    """Raised when a source module cannot be bundled."""


def _module_body(name):
    path = PACKAGE / f'{name}.py'
    if not path.is_file():
        raise BuildError(f'Missing source module: {path}')
    lines = path.read_text().splitlines()
    if lines and DOCSTRING.match(lines[0]):
        lines = lines[1:]
    body = []
    skipping_import = False
    for line in lines:
        if skipping_import:
            if ')' in line:
                skipping_import = False
            continue
        if INTERNAL_IMPORT.match(line):
            skipping_import = '(' in line and line.count('(') > line.count(')')
            continue
        body.append(line)
    while body and not body[0].strip():
        body.pop(0)
    while body and not body[-1].strip():
        body.pop()
    if not body:
        raise BuildError(f'Source module is empty: {path}')
    return '\n'.join(body)


def _validate_module_set():
    actual = {
        path.stem for path in PACKAGE.glob('*.py')
        if path.stem not in {'__init__', '__main__'}
    }
    expected = set(MODULES)
    missing = sorted(expected - actual)
    unlisted = sorted(actual - expected)
    if missing:
        raise BuildError(f'Listed modules not found: {", ".join(missing)}')
    if unlisted:
        raise BuildError(
            f'Modules not listed in MODULES: {", ".join(unlisted)}')


def render():
    _validate_module_set()
    version = (PACKAGE / 'constants.py').read_text()
    match = re.search(r"^__version__\s*=\s*['\"]([^'\"]+)['\"]", version, re.M)
    if not match:
        raise BuildError('Cannot read __version__ from secretpulse/constants.py')
    parts = [HEADER.format(version=match.group(1)).rstrip()]
    for name in MODULES:
        parts.append(f'# ═══ module: {name} ' + '═' * 55)
        parts.append(_module_body(name))
    content = '\n\n'.join(parts).rstrip() + FOOTER
    try:
        compile(content, 'SecretPulse.py', 'exec')
    except SyntaxError as exc:
        raise BuildError(f'Generated bundle has a syntax error: {exc}') from exc
    return content


def write_bundle(output, content):
    output = Path(output)
    output.parent.mkdir(parents=True, exist_ok=True)
    temp = output.with_name(output.name + '.tmp')
    temp.write_text(content)
    os.replace(temp, output)


def main(argv=None):
    parser = argparse.ArgumentParser(
        description='Build the SecretPulse single-file distribution.')
    parser.add_argument('--output', default=str(DEFAULT_OUTPUT),
                        help='Output path (default: SecretPulse.py)')
    parser.add_argument('--check', action='store_true',
                        help='Exit 1 if the existing output is stale')
    args = parser.parse_args(argv)
    try:
        content = render()
    except BuildError as exc:
        print(f'Build error: {exc}', file=sys.stderr)
        return 2
    output = Path(args.output)
    if args.check:
        current = output.read_text() if output.is_file() else ''
        if current != content:
            print(f'Stale bundle: {output}', file=sys.stderr)
            return 1
        print(f'Bundle is current: {output}')
        return 0
    write_bundle(output, content)
    print(f'Wrote {output} ({len(content.splitlines())} lines, '
          f'{len(MODULES)} modules)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
